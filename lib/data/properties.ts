// Индексы и выборки ──────────────────────────────────────────────
export function getProperty(slugOrId: string): Property | undefined {
  return properties.find((p) => p.slug === slugOrId || p.id === slugOrId);
}

export function getSimilar(p: Property, limit = 3): Property[] {
  return properties
    .filter((x) => x.id !== p.id)
    .map((x) => {
      let score = 0;
      if (x.category === p.category) score += 3;
      if (x.district === p.district) score += 2;
      if (x.tier === p.tier) score += 1;
      const priceGap = Math.abs(x.price - p.price) / Math.max(p.price, 1);
      if (priceGap < 0.4) score += 2;
      return { x, score };
    })
    .sort((a, b) => b.score - a.score)
    .slice(0, limit)
    .map((r) => r.x);
}

export function propertiesByBroker(brokerId: string): Property[] {
  return properties.filter((p) => p.brokerId === brokerId);
}

export function featured(limit = 6): Property[] {
  const order = ["Топ недели", "Эксклюзив", "Elite", "Инвестиция"];
  return [...properties]
    .sort((a, b) => {
      const ai = a.badge ? order.indexOf(a.badge) : 99;
      const bi = b.badge ? order.indexOf(b.badge) : 99;
      return (ai < 0 ? 99 : ai) - (bi < 0 ? 99 : bi);
    })
    .slice(0, limit);
}

export const premiumProperties = () =>
  properties.filter((p) => p.tier === "premium" || p.tier === "elite");

export const landProperties = () =>
  properties.filter((p) => p.category === "land");

export const foreignProperties = () => properties.filter((p) => p.isForeign);
